"""Слово-активатор в начале фразы: «Крабик» и «Саня». uv run python test_wake.py"""
import sys

from main import split_wake

CASES = [
    ("крабик", "Крабик, открой блокнот", True, "открой блокнот"),
    ("крабик", "Эй, краб, который час?", True, "который час?"),
    ("крабик", "Краб на ужин был вкусный", True, "на ужин был вкусный"),  # «краб» — обращение, так было и раньше
    ("крабик", "Крабовые палочки купи", False, ""),
    ("крабик", "Позови крабика", False, ""),
    ("саня", "Саня, открой Озон", True, "открой Озон"),
    ("саня", "Санечка, найди погоду", True, "найди погоду"),
    ("саня", "Санька, привет", True, "привет"),
    ("саня", "Эй, Саня! Покажи экран.", True, "Покажи экран."),
    ("саня", "Сань, ты тут?", True, "ты тут?"),
    ("саня", "Сегодня Саня такая милая", False, ""),
    ("саня", "Санаторий хороший получился", False, ""),
    ("саня", "Санки купи", True, "купи"),  # редкость; цена короткой основы
]

if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    bad = 0
    for word, text, ok, rest in CASES:
        got = split_wake(text, word)
        good = got == (ok, rest)
        bad += not good
        print(("✓" if good else "✗"), word, "|", text, "->", got)
    sys.exit(1 if bad else 0)
